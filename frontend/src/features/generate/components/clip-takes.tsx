import { useTranslation } from 'react-i18next'
import { Check, Heart } from 'lucide-react'
import { toast } from 'sonner'
import { Button } from '@/components/ui/button'
import { cn } from '@/shared/ui/cn'
import { useGenerateStore } from '../stores/generate-store'
import { generateApi, type Job } from '../services/generate-api'
import { replaceClipMedia } from '../services/timeline-actions'
import { relativeMoment } from '../deps/studio'

/** What makes two runs takes of one request: the same task and model asked with the same values, the seed aside. */
function requestKey(job: Job): string {
  const values = Object.fromEntries(
    Object.entries(job.values)
      .filter(([key]) => !/seed/i.test(key))
      .toSorted(([a], [b]) => a.localeCompare(b)),
  )
  return JSON.stringify([job.task, job.provider, job.model, values])
}

function failed(error: unknown): void {
  toast.error(error instanceof Error ? error.message : String(error))
}

/**
 * The takes of the request a clip's media was generated by, as Dub Studio keeps the takes of a phrase: each one
 * liked or not, and any of them put in the clip's place.
 */
export function ClipTakes({ clipId, mediaId }: { clipId: string; mediaId: string }) {
  const { t, i18n } = useTranslation()
  const jobs = useGenerateStore((state) => state.jobs)
  const own = jobs.find((job) => job.imported.includes(mediaId))
  if (!own) return null
  const position = own.imported.indexOf(mediaId)
  const key = requestKey(own)
  const takes = jobs
    .filter((job) => job.status === 'done' && job.imported.length > 0 && requestKey(job) === key)
    .toSorted((a, b) => a.created - b.created)
  if (takes.length < 2) return null

  return (
    <section className="space-y-1.5">
      <p className="text-[11px] font-semibold uppercase tracking-wide text-muted-foreground">
        {t('generate.takes.title', { count: takes.length })}
      </p>
      <ul className="space-y-1">
        {takes.map((job, index) => {
          const takeMedia = job.imported[position] ?? job.imported[0]!
          const current = takeMedia === mediaId
          return (
            <li
              key={job.id}
              className={cn(
                'flex items-center gap-1.5 rounded border px-2 py-1 text-[11px]',
                current ? 'border-[var(--color-accent)] bg-secondary/40' : 'border-border',
              )}
            >
              <span className="font-medium">{t('generate.takes.take', { n: index + 1 })}</span>
              <span className="min-w-0 flex-1 truncate text-muted-foreground">{relativeMoment(new Date(job.created), i18n.language)}</span>
              <Button
                size="sm"
                variant="ghost"
                className={cn('h-6 px-1.5', job.liked ? 'text-[var(--color-accent)]' : 'text-muted-foreground')}
                title={job.liked ? t('generate.actions.unlike') : t('generate.actions.like')}
                aria-label={job.liked ? t('generate.actions.unlike') : t('generate.actions.like')}
                aria-pressed={job.liked}
                onClick={() =>
                  void generateApi
                    .like(job.id, !job.liked)
                    .then((updated) => useGenerateStore.getState().upsertJob(updated), failed)
                }
              >
                <Heart className={cn('h-3 w-3', job.liked && 'fill-current')} />
              </Button>
              {current ? (
                <span className="inline-flex items-center gap-1 px-1.5 text-[var(--color-accent)]">
                  <Check className="h-3 w-3" />
                  {t('generate.takes.inClip')}
                </span>
              ) : (
                <Button
                  size="sm"
                  variant="ghost"
                  className="h-6 px-1.5 text-[11px]"
                  title={t('generate.takes.useHint')}
                  onClick={() => {
                    try {
                      replaceClipMedia(clipId, takeMedia)
                    } catch (error) {
                      failed(error)
                    }
                  }}
                >
                  {t('generate.takes.use')}
                </Button>
              )}
            </li>
          )
        })}
      </ul>
    </section>
  )
}
